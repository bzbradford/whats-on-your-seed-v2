    </p>
    <h3>Downloads &amp; citations</h3>
    <dl class="abbreviation-list">
      <div>
        <dt>CSV</dt>
        <dd>
          <strong>Comma-separated values.</strong> A data file that can be opened in Excel or other spreadsheet
          software.
        </dd>
      </div>
      <div>
        <dt>DOI</dt>
        <dd>
          <strong>Digital object identifier.</strong> A persistent identifier used to find and cite a
          publication, when one has been assigned.
        </dd>
      </div>
      <div>
        <dt>PDF</dt>
        <dd>
          <strong>Portable Document Format.</strong> A document format used for product labels and printable
          references.
        </dd>
      </div>
    </dl>
