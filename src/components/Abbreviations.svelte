<article class="panel full abbreviations" id="abbreviations">
  <h3>Abbreviations &amp; terms</h3>
  <p>
    Full names and plain-language explanations for abbreviations used in product information,
    treatment guidance, and source references.
  </p>
  <h4>Ingredients &amp; resistance</h4>
  <dl class="abbreviation-list">
    <div>
      <dt>AI / a.i.</dt>
      <dd>
        <strong>Active ingredient.</strong> The component responsible for a pesticide’s intended pest-control
        effect.
      </dd>
    </div>
    <div>
      <dt>DMI</dt>
      <dd>
        <strong>Demethylation inhibitor.</strong> A fungicide group that disrupts sterol production in
        fungi; FRAC group 3.
      </dd>
    </div>
    <div>
      <dt>FRAC</dt>
      <dd>
        <strong>Fungicide Resistance Action Committee.</strong> The organization behind the fungicide
        resistance-group codes shown in this tool.
      </dd>
    </div>
    <div>
      <dt>IRAC</dt>
      <dd>
        <strong>Insecticide Resistance Action Committee.</strong> The organization behind the insecticide
        mode-of-action codes shown in this tool.
      </dd>
    </div>
    <div>
      <dt>MBC</dt>
      <dd>
        <strong>Methyl benzimidazole carbamate.</strong> A fungicide group that interferes with fungal
        cell division; FRAC group 1.
      </dd>
    </div>
    <div>
      <dt>MOA / MoA</dt>
      <dd>
        <strong>Mode of action.</strong> How a pesticide affects a biological process in its target organism.
      </dd>
    </div>
    <div>
      <dt>QoI</dt>
      <dd>
        <strong>Quinone outside inhibitor.</strong> A fungicide group that interrupts fungal respiration.
        The ingredient guide identifies the applicable FRAC code.
      </dd>
    </div>
    <div>
      <dt>SDHI</dt>
      <dd>
        <strong>Succinate dehydrogenase inhibitor.</strong> A fungicide group that interrupts fungal respiration;
        FRAC group 7.
      </dd>
    </div>
  </dl>
  <p class="small">
    FRAC and IRAC use separate classification systems. Their codes describe resistance groups, not
    ratings of safety or effectiveness. References: <a
      href="https://www.frac.info/media/bfjnhtl5/frac-code-list-2026.pdf"
      target="_blank"
      rel="noopener noreferrer"
    >
      FRAC code list (PDF, new tab)
    </a>
    and
    <a href="https://irac-online.org/mode-of-action/" target="_blank" rel="noopener noreferrer">
      IRAC classification (new tab)
    </a>.
  </p>
  <h4>Safety &amp; handling</h4>
  <dl class="abbreviation-list">
    <div>
      <dt>BMP / BMPs</dt>
      <dd>
        <strong>Best management practice(s).</strong> Practices intended to improve handling and reduce
        unintended impacts.
      </dd>
    </div>
    <div>
      <dt>IPM</dt>
      <dd>
        <strong>Integrated pest management.</strong> An approach combining pest identification, monitoring,
        prevention, and appropriate control methods.
      </dd>
    </div>
    <div>
      <dt>PPE</dt>
      <dd>
        <strong>Personal protective equipment.</strong> Protective clothing and equipment; use the current
        label to identify what is required.
      </dd>
    </div>
    <div>
      <dt>RUP</dt>
      <dd>
        <strong>Restricted-use pesticide.</strong> Refers to restricted-use classification. The tool displays
        the EPA export’s reported flag; check the current label for requirements.
      </dd>
    </div>
    <div>
      <dt>SDS</dt>
      <dd>
        <strong>Safety data sheet.</strong> A document describing chemical hazards and protective measures.
        Read it alongside the pesticide label.
      </dd>
    </div>
  </dl>
  <p class="small">
    References: <a
      href="https://www.epa.gov/safepestcontrol/integrated-pest-management-ipm-principles"
      target="_blank"
      rel="noopener noreferrer"
    >
      EPA’s IPM principles (new tab)
    </a>,
    <a
      href="https://www.epa.gov/pesticide-labels/bilingual-labeling-questions-answers"
      target="_blank"
      rel="noopener noreferrer"
    >
      EPA labeling terminology (new tab)
    </a>, and
    <a
      href="https://www.osha.gov/Publications/OSHA3514.html"
      target="_blank"
      rel="noopener noreferrer"
    >
      OSHA’s safety data sheet guide (new tab)
    </a>.
  </p>
  <h4>Organizations &amp; data sources</h4>
  <dl class="abbreviation-list">
    <div>
      <dt>APPRIL</dt>
      <dd>
        <strong>Active Pesticide Product Registration Informational Listing.</strong> The EPA database
        whose Excel export supplies this catalog’s product records.
      </dd>
    </div>
    <div>
      <dt>CDMS</dt>
      <dd>
        <strong>Crop Data Management Systems.</strong> A provider of agricultural product information;
        saved references are identified separately from EPA records.
      </dd>
    </div>
    <div>
      <dt>CPN</dt>
      <dd>
        <strong>Crop Protection Network.</strong> The agricultural education network associated with this
        tool.
      </dd>
    </div>
    <div>
      <dt>DP</dt>
      <dd>
        <strong>Distributor product.</strong> An EPA registration-type code in the source export. Keep
        the full distributor registration number when identifying a product.
      </dd>
    </div>
    <div>
      <dt>EPA</dt>
      <dd>
        <strong>U.S. Environmental Protection Agency.</strong> The federal agency that supplies the registration
        data used here.
      </dd>
    </div>
    <div>
      <dt>PPLS</dt>
      <dd>
        <strong>Pesticide Product Label System.</strong> EPA’s searchable collection of pesticide product
        labels.
      </dd>
    </div>
    <div>
      <dt>Sec3</dt>
      <dd>
        <strong>Section 3 product.</strong> EPA’s registration-type code for a product registered under
        section 3 of the Federal Insecticide, Fungicide, and Rodenticide Act.
      </dd>
    </div>
  </dl>
  <p class="small">
    Reference: <a
      href="https://www.epa.gov/ingredients-used-pesticide-products/how-search-information-about-pesticide-ingredients-and-labels"
      target="_blank"
      rel="noopener noreferrer"
    >
      EPA database names and registration codes (new tab)
    </a>.
  </p>
  <h4>Downloads &amp; citations</h4>
  <dl class="abbreviation-list">
    <div>
      <dt>CSV</dt>
      <dd>
        <strong>Comma-separated values.</strong> A data file that can be opened in Excel or other spreadsheet
        software.
      </dd>
    </div>
    <div>
      <dt>DOI</dt>
      <dd>
        <strong>Digital object identifier.</strong> A persistent identifier used to find and cite a publication,
        when one has been assigned.
      </dd>
    </div>
    <div>
      <dt>PDF</dt>
      <dd>
        <strong>Portable Document Format.</strong> A document format used for product labels and printable
        references.
      </dd>
    </div>
  </dl>
